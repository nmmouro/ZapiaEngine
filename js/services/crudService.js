// ============================================================================
// SERVICE CRUD GENÉRICO
// Arquivo: js/services/crudService.js
//
// Responsável por centralizar as operações CRUD
// utilizadas pelos serviços da aplicação
// ============================================================================

import {
    listar,
    buscar,
    salvar,
    editar,
    excluir
} from "../api/api.js";


// ============================================================================
// CRIAR SERVIÇO CRUD
// ============================================================================

export function criarCrud(aba) {

    return {

        // ================================================================
        // LISTAR
        // ================================================================

        listar() {
            return listar(aba);
        },


        // ================================================================
        // BUSCAR POR ID
        // ================================================================

        buscar(id) {
            return buscar(aba, id);
        },


        // ================================================================
        // SALVAR
        // ================================================================

        salvar(dados) {
            return salvar(aba, dados);
        },


        // ================================================================
        // EDITAR
        // ================================================================

        editar(id, dados) {
            return editar(aba, id, dados);
        },


        // ================================================================
        // EXCLUIR
        // ================================================================

        excluir(id) {
            return excluir(aba, id);
        }

    };

}
