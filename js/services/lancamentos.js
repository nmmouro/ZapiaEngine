import {

    listar,
    buscar,
    salvar,
    editar,
    excluir

} from "../api/api.js";

// ============================================================================
// CONSTANTES
// ============================================================================

const ABA = "LANCAMENTOS";

// ============================================================================
// LISTAR
// ============================================================================

export function obterLancamentos() {

    return listar(

        ABA

    );

}

// ============================================================================
// BUSCAR
// ============================================================================

export function obterLancamento(id) {

    return buscar(

        ABA,

        id

    );

}

// ============================================================================
// SALVAR
// ============================================================================

export function salvarLancamento(dados) {

    return salvar(

        ABA,

        dados

    );

}

// ============================================================================
// EDITAR
// ============================================================================

export function atualizarLancamento(

    id,

    dados

) {

    return editar(

        ABA,

        id,

        dados

    );

}

// ============================================================================
// EXCLUIR
// ============================================================================

export function excluirLancamento(id) {

    return excluir(

        ABA,

        id

    );

}
