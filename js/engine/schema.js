// ============================================================================
// SCHEMA ENGINE
// Painel Frota
// Arquivo: js/engine/schema.js
// Responsável pelo gerenciamento dos Schemas do Framework.
// ============================================================================

// ============================================================================
// CACHE
// ============================================================================

const schemas = new Map();

// ============================================================================
// CREATE
// ============================================================================

export function createSchema({

    entity,

    title = "",

    icon = "",

    primaryKey = "ID",

    fields = []

}) {

    const schema = {

        entity,

        title,

        icon,

        primaryKey,

        fields

    };

    schemas.set(

        entity,

        schema

    );

    return schema;

}

// ============================================================================
// GET
// ============================================================================

export function getSchema(

    entity

) {

    return schemas.get(

        entity

    );

}

// ============================================================================
// REMOVE
// ============================================================================

export function removeSchema(

    entity

) {

    schemas.delete(

        entity

    );

}

// ============================================================================
// EXISTS
// ============================================================================

export function hasSchema(

    entity

) {

    return schemas.has(

        entity

    );

}

// ============================================================================
// LIST
// ============================================================================

export function getSchemas() {

    return [

        ...schemas.values()

    ];

}

// ============================================================================
// CLEAR
// ============================================================================

export function clearSchemas() {

    schemas.clear();

}

// ============================================================================
// FIELD
// ============================================================================

export function getField(

    entity,

    name

) {

    return getSchema(

        entity

    )

        ?.fields

        .find(

            field =>

                field.name ===

                name

        );

}

// ============================================================================
// FIELDS
// ============================================================================

export function getFields(

    entity

) {

    return (

        getSchema(

            entity

        )?.fields ??

        []

    );

}

// ============================================================================
// FORM FIELDS
// ============================================================================

export function getFormFields(

    entity

) {

    return getFields(

        entity

    ).filter(

        field =>

            field.form !== false

    );

}

// ============================================================================
// TABLE FIELDS
// ============================================================================

export function getTableFields(

    entity

) {

    return getFields(

        entity

    ).filter(

        field =>

            field.table !== false

    );

}

// ============================================================================
// FILTER FIELDS
// ============================================================================

export function getFilterFields(

    entity

) {

    return getFields(

        entity

    ).filter(

        field =>

            field.filter === true

    );

}

// ============================================================================
// REQUIRED
// ============================================================================

export function getRequiredFields(

    entity

) {

    return getFields(

        entity

    ).filter(

        field =>

            field.required

    );

}
